"""
report_agent.py
Generates downloadable, comprehensive PDF and Markdown reports for ArthMitra users.
"""
from typing import Dict, Any
import io
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

class ReportAgent:
    def generate_markdown(self, user_name: str, profile: Dict[str, Any], analysis: Dict[str, Any]) -> str:
        score_data = analysis.get("health_score", {})
        cf = analysis.get("cashflow", {})
        em = analysis.get("emergency", {})
        debt = analysis.get("debt", {})
        goals = analysis.get("goals", {}).get("goals", [])
        alloc = analysis.get("allocation", {}).get("categories", [])
        plan = analysis.get("action_plan", [])
        
        md = f"""# ArthMitra Personalized Financial Plan
**Client:** {user_name} | **Age:** {profile.get('age', 28)} | **Risk Appetite:** {profile.get('risk_appetite', 'Medium')}

> **Regulatory Disclaimer**: This is educational guidance, not registered investment advice. Please consult a SEBI-registered advisor before investing. Data remains on your personal instance and is never sold.

---

## 1. Executive Summary & Financial Health Score
- **Financial Health Score:** **{score_data.get('score', 0)}/100** ({score_data.get('band', 'Fair')})
- **Summary:** {score_data.get('summary', '')}

### Sub-Score Breakdown:
"""
        for s in score_data.get("sub_scores", []):
            md += f"- **{s['name']}** ({s['score']}/100, Weight: {s['weight']}): {s['reason']}\n"
            
        md += f"""
---

## 2. Monthly Cashflow & Savings Velocity
- **Monthly Income:** ₹{cf.get('monthly_income', 0):,.2f}
- **Fixed Obligations & EMIs:** ₹{cf.get('total_fixed_expenses', 0):,.2f}
- **Variable Expenses:** ₹{cf.get('total_variable_expenses', 0):,.2f}
- **Net Savings Capacity:** ₹{cf.get('savings_capacity', 0):,.2f} ({cf.get('savings_rate', 0):.1f}% of income)
- **Status:** {cf.get('realism_status', '')} - {cf.get('realism_note', '')}

### Recommended Discretionary Trims:
"""
        for cut in cf.get("top_cuts", []):
            md += f"- **{cut['category']}**: Currently ₹{cut['current_spend']:,.0f}/mo. {cut['tip']}\n"
            
        md += f"""
---

## 3. Emergency Cushion Plan
- **Target Cushion:** {em.get('target_months', 6)} months of essential survival expenses = **₹{em.get('target_amount', 0):,.2f}**
- **Current Reserves:** ₹{em.get('current_amount', 0):,.2f} ({em.get('months_covered', 0):.1f} months covered)
- **Reserve Gap:** ₹{em.get('gap', 0):,.2f}
- **Pace:** Allocate ₹{em.get('recommended_monthly_allocation', 0):,.2f}/month (Estimated {em.get('months_to_fill', 0)} months to full safety)

---

## 4. Debt Management & Payoff Strategy
"""
        if debt.get("has_loans"):
            md += f"""- **Total Debt Outstanding:** ₹{debt.get('total_debt', 0):,.2f}
- **Debt-To-Income (DTI):** {debt.get('dti_ratio', 0):.1f}% ({debt.get('dti_status', '')})
- **Primary Priority:** Pay **{debt.get('pay_this_first', {}).get('loan_name', 'Highest Rate Loan')}** first (Interest Rate: {debt.get('pay_this_first', {}).get('interest_rate', 0)}%).
- **Prepayment Benefit:** Accelerating payoff saves approximately ₹{debt.get('avalanche_plan', {}).get('interest_saved_vs_baseline', 0):,.0f} in unnecessary interest drag!
"""
        else:
            md += "- **Debt Status:** 100% Debt-Free! Zero loan interest obligations.\n"
            
        md += f"""
---

## 5. Life Goals Feasibility
| Goal Name | Target (FV) | Target Date | Req. Monthly SIP | Feasibility | Suggested Action |
|:---|:---|:---|:---|:---|:---|
"""
        for g in goals:
            md += f"| {g['name']} | ₹{g['future_target_amount']:,.0f} | {g['target_date']} | ₹{g['required_monthly_sip']:,.0f} | **{g['feasibility']}** | {g['suggested_fix']} |\n"
            
        md += f"""
---

## 6. Target Asset Allocation
| Category | Allocation | Monthly SIP Amount | Expected Long-Term Return |
|:---|:---|:---|:---|
"""
        for a in alloc:
            md += f"| {a['name']} | {a['percentage']}% | ₹{a['monthly_amount']:,.0f} | {a['expected_return']} |\n"
            
        md += f"""
**Rationale:** {analysis.get('allocation', {}).get('rationale', '')}

---

## 7. Next 3-Month Action Checklist
"""
        for item in plan:
            status_box = "[x]" if item.get("completed") else "[ ]"
            md += f"- {status_box} **Step {item['step']} ({item['category']})**: {item['action']} — *Timing: {item['timing']}*\n  _{item['reason']}_\n"
            
        md += "\n---\n*Report generated by ArthMitra AI Financial Coach.*"
        return md

    def generate_pdf(self, user_name: str, profile: Dict[str, Any], analysis: Dict[str, Any]) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=18, textColor=colors.HexColor('#0F172A'), spaceAfter=8)
        subtitle_style = ParagraphStyle('SubStyle', parent=styles['Normal'], fontSize=9, textColor=colors.HexColor('#64748B'), spaceAfter=14)
        h2_style = ParagraphStyle('H2Style', parent=styles['Heading2'], fontSize=12, textColor=colors.HexColor('#1E293B'), spaceBefore=10, spaceAfter=6)
        body_style = ParagraphStyle('BodyStyle', parent=styles['Normal'], fontSize=8.5, textColor=colors.HexColor('#334155'), leading=11)
        disclaimer_style = ParagraphStyle('DiscStyle', parent=styles['Italic'], fontSize=7.5, textColor=colors.HexColor('#DC2626'), leading=10)

        story = []
        
        # Header
        story.append(Paragraph("ArthMitra — Comprehensive Financial Plan", title_style))
        story.append(Paragraph(f"Client: <b>{user_name}</b> | Age: {profile.get('age', 28)} | Risk Profile: {profile.get('risk_appetite', 'Medium')}", subtitle_style))
        story.append(Paragraph("<b>Regulatory Disclaimer:</b> This document provides automated educational guidance, not registered investment advice under SEBI (Investment Advisers) Regulations, 2013. Consult a qualified professional before transacting.", disclaimer_style))
        story.append(Spacer(1, 10))

        # Executive Summary & Health Score
        score_data = analysis.get("health_score", {})
        story.append(Paragraph(f"1. Executive Summary — Financial Health Score: {score_data.get('score', 0)}/100 ({score_data.get('band', '')})", h2_style))
        story.append(Paragraph(score_data.get("summary", ""), body_style))
        story.append(Spacer(1, 6))

        # Cashflow Table
        cf = analysis.get("cashflow", {})
        story.append(Paragraph("2. Monthly Cashflow & Savings Overview", h2_style))
        cf_data = [
            ["Metric", "Value", "Benchmark Guidance"],
            ["Monthly Income", f"INR {cf.get('monthly_income', 0):,.0f}", "Baseline inflow"],
            ["Fixed Expenses & EMIs", f"INR {cf.get('total_fixed_expenses', 0):,.0f}", "Target <= 50% of income"],
            ["Variable Expenses", f"INR {cf.get('total_variable_expenses', 0):,.0f}", "Target <= 30% of income"],
            ["Savings Capacity", f"INR {cf.get('savings_capacity', 0):,.0f} ({cf.get('savings_rate', 0):.1f}%)", "Target >= 20% of income"]
        ]
        t_cf = Table(cf_data, colWidths=[150, 150, 240])
        t_cf.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#F1F5F9')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.HexColor('#0F172A')),
            ('FONTNAME', (0,0), (-1,-1), 'Helvetica'),
            ('FONTSIZE', (0,0), (-1,-1), 8),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4)
        ]))
        story.append(t_cf)
        story.append(Spacer(1, 10))

        # Emergency & Debt
        em = analysis.get("emergency", {})
        debt = analysis.get("debt", {})
        story.append(Paragraph("3. Emergency Buffer & Debt Strategy", h2_style))
        story.append(Paragraph(
            f"<b>Emergency Cushion:</b> Target of {em.get('target_months', 6)} months = INR {em.get('target_amount', 0):,.0f}. "
            f"Current reserves cover {em.get('months_covered', 0):.1f} months. Recommended monthly allocation: INR {em.get('recommended_monthly_allocation', 0):,.0f}.",
            body_style
        ))
        if debt.get("has_loans"):
            pay_first = debt.get("pay_this_first", {})
            story.append(Paragraph(
                f"<b>Debt Obligations:</b> Total debt outstanding is INR {debt.get('total_debt', 0):,.0f} with a DTI ratio of {debt.get('dti_ratio', 0):.1f}%. "
                f"Payoff priority: <b>{pay_first.get('loan_name', '')}</b> at {pay_first.get('interest_rate', 0)}% interest. "
                f"Accelerated prepayment saves up to INR {debt.get('avalanche_plan', {}).get('interest_saved_vs_baseline', 0):,.0f} in cumulative interest.",
                body_style
            ))
        else:
            story.append(Paragraph("<b>Debt Obligations:</b> You are completely debt-free.", body_style))
            
        story.append(Spacer(1, 10))

        # Asset Allocation Table
        alloc = analysis.get("allocation", {}).get("categories", [])
        story.append(Paragraph("4. Recommended Asset Allocation (Category-Level)", h2_style))
        alloc_table_data = [["Asset Category", "Share %", "Monthly Inflow", "Expected Return"]]
        for a in alloc:
            alloc_table_data.append([
                a["name"],
                f"{a['percentage']}%",
                f"INR {a['monthly_amount']:,.0f}",
                a["expected_return"]
            ])
        t_alloc = Table(alloc_table_data, colWidths=[240, 70, 110, 120])
        t_alloc.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#F1F5F9')),
            ('FONTNAME', (0,0), (-1,-1), 'Helvetica'),
            ('FONTSIZE', (0,0), (-1,-1), 8),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
            ('TOPPADDING', (0,0), (-1,-1), 4),
            ('BOTTOMPADDING', (0,0), (-1,-1), 4)
        ]))
        story.append(t_alloc)
        story.append(Spacer(1, 10))

        # Action Plan
        plan = analysis.get("action_plan", [])
        story.append(Paragraph("5. 3-Month Priority Execution Checklist", h2_style))
        for p in plan:
            story.append(Paragraph(f"• <b>Step {p['step']} ({p['category']}):</b> {p['action']} (<i>{p['timing']}</i>)<br/>&nbsp;&nbsp;{p['reason']}", body_style))
            story.append(Spacer(1, 3))

        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()

report_agent = ReportAgent()
